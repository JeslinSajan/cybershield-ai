"""
Report Generation Service — Phase 20.

Generates PDF and CSV compliance and executive reports using fpdf2 and standard library csv.
Stores generated reports in backend/generated_reports/.

Supported Report Types:
- security_overview: High-level executive posture, device count, open alerts, vulnerabilities, average risk.
- vulnerability: Detailed technical catalog of discovered CVEs, affected software, and remediation playbooks.
- alert: Incident response audit trail of triggered alerts, severities, triage states, and timestamps.
"""

import csv
import logging
import os
import uuid
from datetime import datetime
from typing import Dict, List, Optional, Tuple

from fpdf import FPDF
from sqlalchemy.orm import Session

from app.models.agent import Agent
from app.models.alert import Alert, RiskScore
from app.models.device import Device
from app.models.organization import Organization
from app.models.report import Report
from app.models.scan import CVE, Vulnerability

logger = logging.getLogger("app.services.report")

REPORT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "generated_reports"))
os.makedirs(REPORT_DIR, exist_ok=True)


def _safe_str(val: Optional[str]) -> str:
    """Sanitize string for core FPDF font encoding (Latin-1 safe)."""
    if val is None:
        return ""
    return str(val).encode("latin-1", "replace").decode("latin-1")


class CyberShieldPDF(FPDF):
    """Custom branded PDF document for CyberShield AI SOC reports."""

    def __init__(self, title_text: str, org_name: str, period_str: str):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.report_title_text = _safe_str(title_text)
        self.org_name = _safe_str(org_name)
        self.period_str = _safe_str(period_str)
        self.set_auto_page_break(auto=True, margin=15)

    def header(self):
        # Header banner
        self.set_fill_color(15, 23, 42)  # Dark slate navy
        self.rect(0, 0, 210, 24, "F")

        # Title text
        self.set_font("Helvetica", "B", 13)
        self.set_text_color(56, 189, 248)  # Cyan
        self.set_xy(10, 5)
        self.cell(0, 7, "CYBERSHIELD AI - SECURITY OPERATIONS PLATFORM", new_x="LMARGIN", new_y="NEXT")

        self.set_font("Helvetica", "", 8)
        self.set_text_color(148, 163, 184)  # Slate
        self.set_x(10)
        self.cell(0, 5, f"Organization: {self.org_name}  |  Period: {self.period_str}", new_x="LMARGIN", new_y="NEXT")

        self.ln(6)

    def footer(self):
        self.set_y(-14)
        self.set_draw_color(203, 213, 225)
        self.line(10, self.get_y(), 200, self.get_y())

        self.set_font("Helvetica", "I", 7)
        self.set_text_color(100, 116, 139)
        self.cell(0, 8, "CONFIDENTIAL - Strictly for Authorized Security Personnel  |  Generated by CyberShield AI", new_x="RIGHT", new_y="TOP")
        self.cell(0, 8, f"Page {self.page_no()}/{{nb}}", align="R", new_x="LMARGIN", new_y="NEXT")


class ReportService:
    """Handles report generation, data extraction, and file persistence."""

    @staticmethod
    def _fetch_report_data(
        db: Session,
        org_id: uuid.UUID,
        report_type: str,
        period_start: datetime,
        period_end: datetime,
    ) -> Dict:
        """Gather telemetry rows from database within assessment timeframe."""
        org = db.query(Organization).filter(Organization.id == org_id).first()
        org_name = org.name if org else "Default Organization"

        if report_type == "security_overview":
            devices = db.query(Device).filter(Device.organization_id == org_id).all()
            agents = db.query(Agent).filter(Agent.organization_id == org_id).all()
            alerts = (
                db.query(Alert)
                .filter(
                    Alert.organization_id == org_id,
                    Alert.created_at >= period_start,
                    Alert.created_at <= period_end,
                )
                .all()
            )
            vulns = (
                db.query(Vulnerability)
                .filter(
                    Vulnerability.organization_id == org_id,
                    Vulnerability.created_at >= period_start,
                    Vulnerability.created_at <= period_end,
                )
                .all()
            )
            risks = (
                db.query(RiskScore)
                .filter(
                    RiskScore.organization_id == org_id,
                    RiskScore.entity_type == "device",
                )
                .all()
            )

            avg_risk = sum(r.score for r in risks) / len(risks) if risks else 0.0

            return {
                "org_name": org_name,
                "total_devices": len(devices),
                "total_agents": len(agents),
                "online_agents": sum(1 for a in agents if a.status == "ONLINE"),
                "total_alerts": len(alerts),
                "critical_alerts": sum(1 for a in alerts if a.severity == "Critical"),
                "high_alerts": sum(1 for a in alerts if a.severity == "High"),
                "medium_alerts": sum(1 for a in alerts if a.severity == "Medium"),
                "low_alerts": sum(1 for a in alerts if a.severity == "Low"),
                "open_alerts": sum(1 for a in alerts if a.status in ("Open", "Acknowledged", "Investigating")),
                "total_vulns": len(vulns),
                "open_vulns": sum(1 for v in vulns if v.status == "open"),
                "avg_risk_score": round(avg_risk, 1),
                "alerts_list": alerts[:15],
                "vulns_list": vulns[:15],
            }

        elif report_type == "vulnerability":
            vulns = (
                db.query(Vulnerability)
                .filter(
                    Vulnerability.organization_id == org_id,
                    Vulnerability.created_at >= period_start,
                    Vulnerability.created_at <= period_end,
                )
                .order_by(Vulnerability.score.desc().nullslast())
                .all()
            )

            # Map CVE and device metadata
            items = []
            for v in vulns:
                cve = db.query(CVE).filter(CVE.id == v.cve_id).first() if v.cve_id else None
                dev = db.query(Device).filter(Device.id == v.device_id).first() if v.device_id else None
                items.append({
                    "id": str(v.id),
                    "cve_id": cve.cve_id if cve else "CVE-UNKNOWN",
                    "device_ip": str(dev.ip_address) if dev else "N/A",
                    "severity": v.severity,
                    "score": float(v.score) if v.score is not None else (cve.cvss_score if cve else 0.0),
                    "service": cve.affected_service if cve else "General",
                    "version": cve.affected_version if cve else "N/A",
                    "status": v.status,
                    "recommendation": v.recommendation or (cve.recommendation if cve else "Patch software"),
                    "created_at": v.created_at.strftime("%Y-%m-%d %H:%M") if v.created_at else "N/A",
                })

            return {"org_name": org_name, "items": items}

        elif report_type == "alert":
            alerts = (
                db.query(Alert)
                .filter(
                    Alert.organization_id == org_id,
                    Alert.created_at >= period_start,
                    Alert.created_at <= period_end,
                )
                .order_by(Alert.triggered_at.desc())
                .all()
            )

            items = []
            for a in alerts:
                dev = db.query(Device).filter(Device.id == a.device_id).first() if a.device_id else None
                items.append({
                    "id": str(a.id),
                    "alert_type": a.alert_type,
                    "severity": a.severity,
                    "status": a.status,
                    "risk_score": float(a.risk_score) if a.risk_score is not None else 0.0,
                    "device_ip": str(dev.ip_address) if dev else "N/A",
                    "description": a.description,
                    "triggered_at": a.triggered_at.strftime("%Y-%m-%d %H:%M") if a.triggered_at else "N/A",
                })

            return {"org_name": org_name, "items": items}

        else:
            return {"org_name": org_name, "items": []}

    @classmethod
    def generate_pdf(
        cls,
        db: Session,
        report: Report,
    ) -> str:
        """Generate a branded PDF report file and return the absolute file path."""
        p_start = report.period_start.strftime("%Y-%m-%d")
        p_end = report.period_end.strftime("%Y-%m-%d")
        period_str = f"{p_start} to {p_end}"

        title_map = {
            "security_overview": "Executive Security Overview Report",
            "vulnerability": "Vulnerability & CVE Assessment Report",
            "alert": "Incident & Threat Alert Audit Report",
        }
        title_text = title_map.get(report.report_type, "CyberShield Security Report")

        data = cls._fetch_report_data(
            db,
            report.organization_id,
            report.report_type,
            report.period_start,
            report.period_end,
        )

        pdf = CyberShieldPDF(title_text=title_text, org_name=data["org_name"], period_str=period_str)
        pdf.alias_nb_pages()
        pdf.add_page()

        # Document Header
        pdf.set_font("Helvetica", "B", 15)
        pdf.set_text_color(15, 23, 42)
        pdf.cell(0, 8, _safe_str(title_text), new_x="LMARGIN", new_y="NEXT")

        pdf.set_font("Helvetica", "", 9)
        pdf.set_text_color(100, 116, 139)
        pdf.cell(0, 5, f"Report ID: {report.id}  |  Generated: {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)

        if report.report_type == "security_overview":
            # Executive Summary Cards
            pdf.set_font("Helvetica", "B", 11)
            pdf.set_text_color(30, 41, 59)
            pdf.cell(0, 6, "1. Executive Summary & Fleet Metrics", new_x="LMARGIN", new_y="NEXT")
            pdf.ln(1)

            # Metrics Table
            pdf.set_font("Helvetica", "B", 8)
            pdf.set_fill_color(241, 245, 249)
            pdf.set_text_color(51, 65, 85)
            col_w = 47.5

            pdf.cell(col_w, 6, "Total Monitored Devices", 1, new_x="RIGHT", new_y="TOP", align="C", fill=True)
            pdf.cell(col_w, 6, "Active Agent Nodes", 1, new_x="RIGHT", new_y="TOP", align="C", fill=True)
            pdf.cell(col_w, 6, "Active Open Alerts", 1, new_x="RIGHT", new_y="TOP", align="C", fill=True)
            pdf.cell(col_w, 6, "Average Device Risk", 1, new_x="LMARGIN", new_y="NEXT", align="C", fill=True)

            pdf.set_font("Helvetica", "", 10)
            pdf.cell(col_w, 7, str(data["total_devices"]), 1, new_x="RIGHT", new_y="TOP", align="C")
            pdf.cell(col_w, 7, f"{data['online_agents']} / {data['total_agents']}", 1, new_x="RIGHT", new_y="TOP", align="C")
            pdf.cell(col_w, 7, str(data["open_alerts"]), 1, new_x="RIGHT", new_y="TOP", align="C")
            pdf.cell(col_w, 7, f"{data['avg_risk_score']} / 100", 1, new_x="LMARGIN", new_y="NEXT", align="C")
            pdf.ln(4)

            # Alert Distribution Breakdown
            pdf.set_font("Helvetica", "B", 10)
            pdf.cell(0, 6, "2. Alert Severity Breakdown", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 8)
            pdf.cell(47.5, 5, f"Critical: {data['critical_alerts']}", 1, new_x="RIGHT", new_y="TOP", align="L")
            pdf.cell(47.5, 5, f"High: {data['high_alerts']}", 1, new_x="RIGHT", new_y="TOP", align="L")
            pdf.cell(47.5, 5, f"Medium: {data['medium_alerts']}", 1, new_x="RIGHT", new_y="TOP", align="L")
            pdf.cell(47.5, 5, f"Low: {data['low_alerts']}", 1, new_x="LMARGIN", new_y="NEXT", align="L")
            pdf.ln(4)

            # Recommendations
            pdf.set_font("Helvetica", "B", 10)
            pdf.cell(0, 6, "3. SOC Posture Assessment", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 8)
            pdf.multi_cell(
                0,
                4.5,
                _safe_str(
                    f"During the assessment timeframe ({period_str}), CyberShield AI monitored {data['total_devices']} assets. "
                    f"A total of {data['total_alerts']} security incidents and {data['total_vulns']} vulnerability findings were analyzed. "
                    f"The fleet maintains an average asset risk score of {data['avg_risk_score']}. "
                    "Prioritize resolving Critical and High alerts and patch high-scoring CVE vulnerabilities to maintain a hardened defense."
                ),
            )

        elif report.report_type == "vulnerability":
            items = data.get("items", [])
            pdf.set_font("Helvetica", "B", 9)
            pdf.cell(0, 6, f"Discovered Vulnerabilities ({len(items)} total findings in window)", new_x="LMARGIN", new_y="NEXT")
            pdf.ln(1)

            # Table Header
            pdf.set_fill_color(30, 41, 59)
            pdf.set_text_color(255, 255, 255)
            pdf.set_font("Helvetica", "B", 7)
            pdf.cell(32, 6, "CVE Identifier", 1, new_x="RIGHT", new_y="TOP", align="L", fill=True)
            pdf.cell(26, 6, "Affected Host", 1, new_x="RIGHT", new_y="TOP", align="L", fill=True)
            pdf.cell(16, 6, "Severity", 1, new_x="RIGHT", new_y="TOP", align="C", fill=True)
            pdf.cell(14, 6, "CVSS", 1, new_x="RIGHT", new_y="TOP", align="C", fill=True)
            pdf.cell(32, 6, "Service / Ver", 1, new_x="RIGHT", new_y="TOP", align="L", fill=True)
            pdf.cell(70, 6, "Recommended Action", 1, new_x="LMARGIN", new_y="NEXT", align="L", fill=True)

            pdf.set_font("Helvetica", "", 7)
            pdf.set_text_color(30, 41, 59)
            for item in items:
                pdf.cell(32, 5.5, _safe_str(item["cve_id"][:18]), 1, new_x="RIGHT", new_y="TOP", align="L")
                pdf.cell(26, 5.5, _safe_str(item["device_ip"][:15]), 1, new_x="RIGHT", new_y="TOP", align="L")
                pdf.cell(16, 5.5, _safe_str(item["severity"]), 1, new_x="RIGHT", new_y="TOP", align="C")
                pdf.cell(14, 5.5, f"{item['score']:.1f}", 1, new_x="RIGHT", new_y="TOP", align="C")
                pdf.cell(32, 5.5, _safe_str(f"{item['service']} {item['version']}")[:20], 1, new_x="RIGHT", new_y="TOP", align="L")
                pdf.cell(70, 5.5, _safe_str(item["recommendation"][:46]), 1, new_x="LMARGIN", new_y="NEXT", align="L")

        elif report.report_type == "alert":
            items = data.get("items", [])
            pdf.set_font("Helvetica", "B", 9)
            pdf.cell(0, 6, f"Incident & Alert Audit Trail ({len(items)} incidents)", new_x="LMARGIN", new_y="NEXT")
            pdf.ln(1)

            # Table Header
            pdf.set_fill_color(30, 41, 59)
            pdf.set_text_color(255, 255, 255)
            pdf.set_font("Helvetica", "B", 7)
            pdf.cell(28, 6, "Timestamp", 1, new_x="RIGHT", new_y="TOP", align="L", fill=True)
            pdf.cell(28, 6, "Alert Type", 1, new_x="RIGHT", new_y="TOP", align="L", fill=True)
            pdf.cell(16, 6, "Severity", 1, new_x="RIGHT", new_y="TOP", align="C", fill=True)
            pdf.cell(20, 6, "Status", 1, new_x="RIGHT", new_y="TOP", align="C", fill=True)
            pdf.cell(26, 6, "Target IP", 1, new_x="RIGHT", new_y="TOP", align="L", fill=True)
            pdf.cell(72, 6, "Incident Summary", 1, new_x="LMARGIN", new_y="NEXT", align="L", fill=True)

            pdf.set_font("Helvetica", "", 7)
            pdf.set_text_color(30, 41, 59)
            for item in items:
                pdf.cell(28, 5.5, _safe_str(item["triggered_at"]), 1, new_x="RIGHT", new_y="TOP", align="L")
                pdf.cell(28, 5.5, _safe_str(item["alert_type"].replace('_', ' ')[:16]), 1, new_x="RIGHT", new_y="TOP", align="L")
                pdf.cell(16, 5.5, _safe_str(item["severity"]), 1, new_x="RIGHT", new_y="TOP", align="C")
                pdf.cell(20, 5.5, _safe_str(item["status"]), 1, new_x="RIGHT", new_y="TOP", align="C")
                pdf.cell(26, 5.5, _safe_str(item["device_ip"][:15]), 1, new_x="RIGHT", new_y="TOP", align="L")
                pdf.cell(72, 5.5, _safe_str(item["description"][:48]), 1, new_x="LMARGIN", new_y="NEXT", align="L")

        filename = f"cybershield_report_{report.id}.pdf"
        filepath = os.path.join(REPORT_DIR, filename)
        pdf.output(filepath)
        return filepath

    @classmethod
    def generate_csv(
        cls,
        db: Session,
        report: Report,
    ) -> str:
        """Generate a standard CSV export file and return the absolute file path."""
        data = cls._fetch_report_data(
            db,
            report.organization_id,
            report.report_type,
            report.period_start,
            report.period_end,
        )

        filename = f"cybershield_report_{report.id}.csv"
        filepath = os.path.join(REPORT_DIR, filename)

        with open(filepath, "w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)

            if report.report_type == "security_overview":
                writer.writerow(["Metric", "Value"])
                writer.writerow(["Organization", data["org_name"]])
                writer.writerow(["Report Type", report.report_type])
                writer.writerow(["Period Start", report.period_start.isoformat()])
                writer.writerow(["Period End", report.period_end.isoformat()])
                writer.writerow(["Total Devices", data["total_devices"]])
                writer.writerow(["Total Agents", data["total_agents"]])
                writer.writerow(["Online Agents", data["online_agents"]])
                writer.writerow(["Total Alerts", data["total_alerts"]])
                writer.writerow(["Critical Alerts", data["critical_alerts"]])
                writer.writerow(["High Alerts", data["high_alerts"]])
                writer.writerow(["Medium Alerts", data["medium_alerts"]])
                writer.writerow(["Low Alerts", data["low_alerts"]])
                writer.writerow(["Active Open Alerts", data["open_alerts"]])
                writer.writerow(["Total Vulnerabilities", data["total_vulns"]])
                writer.writerow(["Average Device Risk Score", data["avg_risk_score"]])

            elif report.report_type == "vulnerability":
                items = data.get("items", [])
                writer.writerow(["Vulnerability ID", "CVE ID", "Target Host", "Severity", "CVSS Score", "Service", "Version", "Status", "Recommendation", "Discovered At"])
                for item in items:
                    writer.writerow([
                        item["id"],
                        item["cve_id"],
                        item["device_ip"],
                        item["severity"],
                        item["score"],
                        item["service"],
                        item["version"],
                        item["status"],
                        item["recommendation"],
                        item["created_at"],
                    ])

            elif report.report_type == "alert":
                items = data.get("items", [])
                writer.writerow(["Alert ID", "Timestamp", "Alert Type", "Severity", "Status", "Risk Score", "Target Host", "Description"])
                for item in items:
                    writer.writerow([
                        item["id"],
                        item["triggered_at"],
                        item["alert_type"],
                        item["severity"],
                        item["status"],
                        item["risk_score"],
                        item["device_ip"],
                        item["description"],
                    ])

        return filepath


report_service = ReportService()
